#!/usr/bin/env python3
"""Writes data/sql/db-world/mod_supply_logistics_world.sql from catalog.py and the data TSVs.

    python3 build_data.py

The rows the client also needs (spells, factions, titles, the currency, prices) are build_patch.py's,
in mod_supply_logistics_dbc.sql. Running it twice writes the same file.

Released under the MIT License.
"""

import os

from catalog import (COSTS, CURRENCY_ID, FACTIONS, MOUNT_SPELLS, PET_SPELLS, USE_SPELLS, KINDS, TEXT_CRATE, TEXT_QUILL, TEXT_RECEIPT, CHEF_GOODS, CONTAINER, COST_ID, CRATE_RETURN, FAVOR, MINIMULE, MULE_MOUNT, NPC, PROFESSION_VENDORS, QUILLS,
                     RECEIPT, RECEIPT_REP, REINS, SEALED, TIER_NAMES, TITLES, TREATS, WRIT_FAVOR, bundles, crates,
                     items, sealed_pay, writs)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "sql", "db-world",
                   "mod_supply_logistics_world.sql")
UNINSTALL = os.path.normpath(os.path.join(os.path.dirname(OUT), "..", "uninstall", "mod_supply_logistics_uninstall_world.sql"))
REPEATABLE = 1                # quest_template_addon.SpecialFlags
HAND_IN_TEXT = "Another delivery! Fantastic. Set it over by the pile and we can discuss your compensation."


def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def ids(values):
    return ", ".join(str(v) for v in sorted(set(values)))


def main():
    all_items = items()
    crate_rows, bundle_rows, writ_rows = crates(), bundles(), writs()
    out = []
    w = out.append

    w("-- mod-supply-logistics: world rows. Generated by tools/build_data.py from tools/catalog.py and data/*.tsv;")
    w("-- change those and run it again rather than editing this file.")
    w("")

    # --- Module tables ---------------------------------------------------------------------------
    w("-- The module's own tables: what each Waylaid Crate takes and becomes, what each writ is, and")
    w("-- the reputation each hand-in pays (the module pays it to the player's own side).")
    w("CREATE TABLE IF NOT EXISTS `mod_supply_logistics_crate` (")
    w("  `item` INT UNSIGNED NOT NULL, `tier` TINYINT UNSIGNED NOT NULL, `crafted` TINYINT UNSIGNED NOT NULL,")
    w("  `kind` TINYINT UNSIGNED NOT NULL,")
    w("  `sealed` INT UNSIGNED NOT NULL, PRIMARY KEY (`item`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;")
    w("CREATE TABLE IF NOT EXISTS `mod_supply_logistics_bundle` (")
    w("  `crate` INT UNSIGNED NOT NULL, `slot` TINYINT UNSIGNED NOT NULL, `reagent` INT UNSIGNED NOT NULL,")
    w("  `count` INT UNSIGNED NOT NULL, PRIMARY KEY (`crate`, `slot`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;")
    w("CREATE TABLE IF NOT EXISTS `mod_supply_logistics_writ` (")
    w("  `writ` INT UNSIGNED NOT NULL, `quest` INT UNSIGNED NOT NULL, `tier` TINYINT UNSIGNED NOT NULL,")
    w("  `skill` SMALLINT UNSIGNED NOT NULL, PRIMARY KEY (`writ`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;")
    w("CREATE TABLE IF NOT EXISTS `mod_supply_logistics_quest` (")
    w("  `quest` INT UNSIGNED NOT NULL, `rep` INT UNSIGNED NOT NULL, PRIMARY KEY (`quest`))")
    w("  ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;")
    w("")
    w("DELETE FROM `mod_supply_logistics_crate`;")
    w("INSERT INTO `mod_supply_logistics_crate` (`item`, `tier`, `crafted`, `kind`, `sealed`) VALUES")
    w(",\n".join("(%d, %d, %d, %d, %d)" % (c["item"], c["tier"], c["group"] == "crafted", KINDS[c["kind"]],
                                           SEALED[(c["group"], c["tier"])][0])
                 for c in crate_rows) + ";")
    w("DELETE FROM `mod_supply_logistics_bundle`;")
    w("INSERT INTO `mod_supply_logistics_bundle` (`crate`, `slot`, `reagent`, `count`) VALUES")
    w(",\n".join("(%d, %d, %d, %d)" % (b["crate"], b["slot"], b["reagent"], b["count"]) for b in bundle_rows) + ";")
    w("DELETE FROM `mod_supply_logistics_writ`;")
    w("INSERT INTO `mod_supply_logistics_writ` (`writ`, `quest`, `tier`, `skill`) VALUES")
    w(",\n".join("(%d, %d, %d, %d)" % (r["writ"], r["quest"], r["tier"], r["skill"]) for r in writ_rows) + ";")
    quest_rep = [(quest, sealed_pay(group, tier)[1]) for (group, tier), (_item, quest) in SEALED.items()]
    quest_rep += [(r["quest"], r["rep"]) for r in writ_rows]
    quest_rep.append((CRATE_RETURN, RECEIPT_REP))
    w("DELETE FROM `mod_supply_logistics_quest`;")
    w("INSERT INTO `mod_supply_logistics_quest` (`quest`, `rep`) VALUES")
    w(",\n".join("(%d, %d)" % qr for qr in sorted(quest_rep)) + ";")
    w("")

    # --- Item menus -----------------------------------------------------------------------------
    w("-- The text over the menus a Waylaid Crate, a Forged Delivery Receipt and a Forger's Quill open.")
    w("DELETE FROM `npc_text` WHERE `ID` IN (%d, %d, %d);" % (TEXT_CRATE, TEXT_RECEIPT, TEXT_QUILL))
    w("INSERT INTO `npc_text` (`ID`, `text0_0`, `Probability0`, `VerifiedBuild`) VALUES")
    w("(%d, %s, 1, 0)," % (TEXT_CRATE, q("The label lists what the shipment should have held. Fill the crate with any "
                                        "one of these bundles and it's sealed, ready for your faction's trade camp.")))
    w("(%d, %s, 1, 0)," % (TEXT_RECEIPT, q("Which crate gets the forged receipt? It goes back to the trade camp empty.")))
    w("(%d, %s, 1, 0);" % (TEXT_QUILL, q("Which writ should be rewritten? A writ whose order you have accepted can't be.")))
    w("")

    # --- Items -----------------------------------------------------------------------------------
    item_ids = [i["entry"] for i in all_items]
    w("-- The items: Forever's ids where Forever has them. Their client rows (icons) are build_patch.py's.")
    w("DELETE FROM `item_template` WHERE `entry` IN (%s);" % ids(item_ids))
    cols = ["entry", "class", "subclass", "SoundOverrideSubclass", "name", "displayid", "Quality", "Flags",
            "BuyCount", "BuyPrice", "SellPrice", "InventoryType", "AllowableClass", "AllowableRace", "ItemLevel",
            "RequiredLevel", "RequiredSkill", "RequiredSkillRank", "RequiredReputationFaction",
            "RequiredReputationRank", "maxcount", "stackable", "spellid_1", "spelltrigger_1", "spellcharges_1",
            "spellcooldown_1", "spellcategorycooldown_1", "spellid_2", "spelltrigger_2", "spellcooldown_2",
            "spellcategorycooldown_2", "bonding", "description", "startquest", "Material", "BagFamily",
            "ScriptName", "VerifiedBuild"]
    w("INSERT INTO `item_template` (%s) VALUES" % ", ".join("`%s`" % c for c in cols))
    lines = []
    for i in all_items:
        row = {
            "entry": i["entry"], "class": i["cls"], "subclass": i["subclass"], "SoundOverrideSubclass": -1,
            "name": q(i["name"]), "displayid": i["display"], "Quality": i["quality"],
            "Flags": 2048 if i["entry"] == FAVOR else i["flags"], "BuyCount": 1, "BuyPrice": 0,
            "SellPrice": i["sell"], "InventoryType": 0, "AllowableClass": -1, "AllowableRace": -1,
            "ItemLevel": max(1, i["level"]), "RequiredLevel": i["level"], "RequiredSkill": i["skill"],
            "RequiredSkillRank": i["skill_rank"], "RequiredReputationFaction": i["rep_faction"],
            "RequiredReputationRank": i["rep_rank"], "maxcount": i["maxcount"], "stackable": i["stackable"],
            "spellid_1": i["spell"], "spelltrigger_1": i["trigger"], "spellcharges_1": 0, "spellcooldown_1": -1,
            "spellcategorycooldown_1": -1, "spellid_2": i["spell2"], "spelltrigger_2": i["trigger2"],
            "spellcooldown_2": -1, "spellcategorycooldown_2": -1, "bonding": i["bonding"],
            "description": q(i["description"]), "startquest": i["startquest"], "Material": i["material"],
            "BagFamily": i["bag_family"], "ScriptName": q(i["script"]), "VerifiedBuild": 0,
        }
        lines.append("(" + ", ".join(str(row[c]) for c in cols) + ")")
    w(",\n".join(lines) + ";")
    w("")

    # --- Creatures -------------------------------------------------------------------------------
    w("-- The Minimule (Packmule Treat's companion) and the Pack Mule mount's look. The Pack Kodo mount")
    w("-- rides stock creature 10636's look.")
    w("DELETE FROM `creature_template_model` WHERE `CreatureID` IN (%d, %d);" % (MINIMULE, MULE_MOUNT))
    w("DELETE FROM `creature_template` WHERE `entry` IN (%d, %d);" % (MINIMULE, MULE_MOUNT))
    w("INSERT INTO `creature_template` (`entry`, `name`, `minlevel`, `maxlevel`, `faction`, `npcflag`, `speed_walk`, "
      "`speed_run`, `unit_class`, `unit_flags`, `unit_flags2`, `type`, `flags_extra`, `movementId`, `VerifiedBuild`) VALUES")
    w("(%d, 'Minimule', 1, 1, 188, 0, 1, 1.14286, 1, 768, 2048, 12, 2, 121, 0)," % MINIMULE)
    w("(%d, 'Pack Mule', 1, 1, 35, 0, 1, 1.14286, 1, 768, 2048, 1, 2, 0, 0);" % MULE_MOUNT)
    w("INSERT INTO `creature_template_model` (`CreatureID`, `Idx`, `CreatureDisplayID`, `DisplayScale`, `Probability`, "
      "`VerifiedBuild`) VALUES")
    w("(%d, 0, 14551, 0.4, 1, 0)," % MINIMULE)
    w("(%d, 0, 14551, 1, 1, 0);" % MULE_MOUNT)
    w("")

    # --- Quests ----------------------------------------------------------------------------------
    quest_ids = [quest for _item, quest in SEALED.values()] + [r["quest"] for r in writ_rows] + [CRATE_RETURN]
    qcols = ["ID", "QuestType", "QuestLevel", "MinLevel", "QuestSortID", "QuestInfoID", "Flags", "RequiredItemId1",
             "RequiredItemCount1", "RequiredItemId2", "RequiredItemCount2", "RewardItem1", "RewardAmount1",
             "LogTitle", "LogDescription", "QuestDescription", "QuestCompletionLog", "VerifiedBuild"]
    qlines, request, offer = [], [], []
    for (group, tier), (item, quest) in sorted(SEALED.items(), key=lambda kv: kv[1][1]):
        favor, _rep = sealed_pay(group, tier)
        name = "Sealed %s Crate" % TIER_NAMES[tier]
        qlines.append("(%d, 2, -1, 10, 0, 0, 0, %d, 1, 0, 0, %d, %d, 'A Sealed Crate', %s, %s, %s, 0)" % (
            quest, item, FAVOR, favor, q("Deliver a %s to your faction's trade representative." % name),
            q("A %s, delivered at last. Hand it over and you'll be paid in Merchant's Favor, and the "
              "camp will remember who brought it." % name),
            q("Return to the Inventory Intake at your faction's trade camp.")))
        request.append((quest, "Is that a %s? Bring it here." % name))
        offer.append((quest, HAND_IN_TEXT))
    qlines.append("(%d, 2, -1, 10, 0, 0, 0, %d, 1, 0, 0, 0, 0, 'Crate Return', %s, %s, %s, 0)" % (
        CRATE_RETURN, CONTAINER, q("Return a Notarized Shipping Container to your faction's trade representative."),
        q("An empty crate, with a delivery receipt on it that looks almost real. We'll take it back all the same: "
          "crates cost money."), q("Return to the Inventory Intake at your faction's trade camp.")))
    request.append((CRATE_RETURN, "An empty one? Let's see the receipt."))
    offer.append((CRATE_RETURN, "Signed and stamped. Close enough. Thanks for bringing it back."))
    for r in writ_rows:
        made = r["name"] if r["count"] == 1 else "%d %s" % (r["count"], r["name"])
        # The writ itself is not an objective: taking the order uses it up (the core destroys a quest's
        # starting item unless it is a required item with a MaxCount).
        qlines.append("(%d, 2, -1, 10, 0, 0, 0, %d, %d, 0, 0, %d, %d, %s, %s, %s, %s, 0)" % (
            r["quest"], r["item"], r["count"], FAVOR, WRIT_FAVOR[r["rep"]], q("Craftsman's Writ: " + r["name"]),
            q("Bring %s to a Contract Coordinator at your faction's trade camp." % made),
            q("<Penned in faded ink, the note asks for %s, with delivery instructions and the promised payment.>" % made),
            q("Return to a Contract Coordinator at your faction's trade camp.")))
        request.append((r["quest"], "An order for us? Let's see whether the goods match it."))
        offer.append((r["quest"], "Exactly what the customer asked for. Here's your payment."))
    w("-- The quests: Forever's ids. A Sealed crate, an empty container or a writ with its goods, handed")
    w("-- in for Merchant's Favor. All repeatable; the module pays the reputation.")
    w("DELETE FROM `quest_template` WHERE `ID` IN (%s);" % ids(quest_ids))
    w("INSERT INTO `quest_template` (%s) VALUES" % ", ".join("`%s`" % c for c in qcols))
    w(",\n".join(qlines) + ";")
    w("DELETE FROM `quest_template_addon` WHERE `ID` IN (%s);" % ids(quest_ids))
    w("INSERT INTO `quest_template_addon` (`ID`, `SpecialFlags`) VALUES")
    w(",\n".join("(%d, %d)" % (quest, REPEATABLE) for quest in sorted(quest_ids)) + ";")
    w("DELETE FROM `quest_request_items` WHERE `ID` IN (%s);" % ids(quest_ids))
    w("INSERT INTO `quest_request_items` (`ID`, `EmoteOnComplete`, `EmoteOnIncomplete`, `CompletionText`, "
      "`VerifiedBuild`) VALUES")
    w(",\n".join("(%d, 1, 1, %s, 0)" % (quest, q(text)) for quest, text in sorted(request)) + ";")
    w("DELETE FROM `quest_offer_reward` WHERE `ID` IN (%s);" % ids(quest_ids))
    w("INSERT INTO `quest_offer_reward` (`ID`, `Emote1`, `RewardText`, `VerifiedBuild`) VALUES")
    w(",\n".join("(%d, 4, %s, 0)" % (quest, q(text)) for quest, text in sorted(offer)) + ";")
    w("")
    intake_quests = [quest for _item, quest in SEALED.values()] + [CRATE_RETURN]
    hand_ins = [(quest, item) for item, quest in SEALED.values()] + [(CRATE_RETURN, CONTAINER)]
    w("-- Each hand-in is offered only while you carry its crate (source type 19, quest available;")
    w("-- condition 2, item), so the Inventory Intake doesn't list all ten at once.")
    w("DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` = 19 AND `SourceEntry` IN (%s);"
      % ids(q_ for q_, _i in hand_ins))
    w("INSERT INTO `conditions` (`SourceTypeOrReferenceId`, `SourceGroup`, `SourceEntry`, `SourceId`, `ElseGroup`, "
      "`ConditionTypeOrReference`, `ConditionTarget`, `ConditionValue1`, `ConditionValue2`, `ConditionValue3`, "
      "`NegativeCondition`, `ErrorType`, `ErrorTextId`, `ScriptName`, `Comment`) VALUES")
    w(",\n".join("(19, 0, %d, 0, 0, 2, 0, %d, 1, 0, 0, 0, 0, '', 'mod-supply-logistics: carries the crate')"
                  % (quest, item) for quest, item in sorted(hand_ins)) + ";")
    w("-- Sealed crates and containers at the Inventory Intake; writs start from their item and end at")
    w("-- the Contract Coordinator. The module gives these NPCs their quest and vendor flags.")
    w("DELETE FROM `creature_queststarter` WHERE `quest` IN (%s);" % ids(quest_ids))
    w("INSERT INTO `creature_queststarter` (`id`, `quest`) VALUES")
    w(",\n".join("(%d, %d)" % (npc, quest) for npc in NPC["intake"] for quest in sorted(intake_quests)) + ";")
    w("DELETE FROM `creature_questender` WHERE `quest` IN (%s);" % ids(quest_ids))
    w("INSERT INTO `creature_questender` (`id`, `quest`) VALUES")
    enders = [(npc, quest) for npc in NPC["intake"] for quest in sorted(intake_quests)]
    enders += [(npc, r["quest"]) for npc in NPC["coordinator"] for r in writ_rows]
    w(",\n".join("(%d, %d)" % e for e in enders) + ";")
    w("")

    # --- Vendors ---------------------------------------------------------------------------------
    stock = []
    for side in (0, 1):
        stock.append((NPC["officer"][side], TREATS[side], COST_ID[1500]))
        stock.append((NPC["handler"][side], REINS[side], COST_ID[6000]))
        stock.append((NPC["scribe"][side], QUILLS[side], COST_ID[15]))
        stock.append((NPC["scribe"][side], RECEIPT, COST_ID[15]))
        for _title, _bit, item, skill, _text in TITLES:
            stock.append((PROFESSION_VENDORS[skill][side], item, COST_ID[1000]))
        for good in CHEF_GOODS:
            stock.append((NPC["chef"][side], good, 0))
    vendors = sorted({v for v, _i, _c in stock})
    w("-- What they sell, priced in Merchant's Favor (ItemExtendedCost, see mod_supply_logistics_dbc.sql).")
    w("-- The recipes come later. Tabards and the shop-sign toy wait for their art.")
    w("DELETE FROM `npc_vendor` WHERE `entry` IN (%s);" % ids(vendors))
    w("INSERT INTO `npc_vendor` (`entry`, `slot`, `item`, `maxcount`, `incrtime`, `ExtendedCost`, `VerifiedBuild`) VALUES")
    slots = {}
    lines = []
    for vendor, item, cost in stock:
        slots[vendor] = slots.get(vendor, -1) + 1
        lines.append("(%d, %d, %d, 0, 0, %d, 0)" % (vendor, slots[vendor], item, cost))
    w(",\n".join(lines) + ";")
    certs = [(PROFESSION_VENDORS[skill][side], item, skill) for _t, _b, item, skill, _x in TITLES for side in (0, 1)]
    w("-- A Certification is sold only to those with 300 skill (source type 23, vendor item; condition 7,")
    w("-- skill): the vendor checks reputation but not skill.")
    w("DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` = 23 AND `SourceGroup` IN (%s);" % ids(v for v, _i, _s in certs))
    w("INSERT INTO `conditions` (`SourceTypeOrReferenceId`, `SourceGroup`, `SourceEntry`, `SourceId`, `ElseGroup`, "
      "`ConditionTypeOrReference`, `ConditionTarget`, `ConditionValue1`, `ConditionValue2`, `ConditionValue3`, "
      "`NegativeCondition`, `ErrorType`, `ErrorTextId`, `ScriptName`, `Comment`) VALUES")
    w(",\n".join("(23, %d, %d, 0, 0, 7, 0, %d, 300, 0, 0, 0, 0, '', 'mod-supply-logistics: 300 skill')" % c
                  for c in sorted(certs)) + ";")
    w("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    write_uninstall(item_ids, quest_ids, vendors)
    print("wrote %s: %d items, %d quests, %d vendor rows" % (OUT, len(all_items), len(quest_ids), len(stock)))


def write_uninstall(item_ids, quest_ids, vendors):
    spells = [s[0] for s in USE_SPELLS] + [s[0] for s in MOUNT_SPELLS] + [s[0] for s in PET_SPELLS]
    lines = [
        "-- mod-supply-logistics: removes every world row the module adds. Generated by tools/build_data.py.",
        "-- Run by hand. Items already in bags and mail become unknown items; the client patch keeps its rows.",
        "DROP TABLE IF EXISTS `mod_supply_logistics_crate`, `mod_supply_logistics_bundle`, `mod_supply_logistics_writ`, "
        "`mod_supply_logistics_quest`;",
        "DELETE FROM `item_template` WHERE `entry` IN (%s);" % ids(item_ids),
        "DELETE FROM `quest_template` WHERE `ID` IN (%s);" % ids(quest_ids),
        "DELETE FROM `quest_template_addon` WHERE `ID` IN (%s);" % ids(quest_ids),
        "DELETE FROM `quest_request_items` WHERE `ID` IN (%s);" % ids(quest_ids),
        "DELETE FROM `quest_offer_reward` WHERE `ID` IN (%s);" % ids(quest_ids),
        "DELETE FROM `creature_queststarter` WHERE `quest` IN (%s);" % ids(quest_ids),
        "DELETE FROM `creature_questender` WHERE `quest` IN (%s);" % ids(quest_ids),
        "DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` = 19 AND `SourceEntry` IN (%s);" % ids(quest_ids),
        "DELETE FROM `npc_vendor` WHERE `entry` IN (%s);" % ids(vendors),
        "DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` = 23 AND `SourceGroup` IN (%s);" % ids(vendors),
        "DELETE FROM `creature_template_model` WHERE `CreatureID` IN (%d, %d);" % (MINIMULE, MULE_MOUNT),
        "DELETE FROM `creature_template` WHERE `entry` IN (%d, %d);" % (MINIMULE, MULE_MOUNT),
        "DELETE FROM `npc_text` WHERE `ID` IN (%d, %d, %d);" % (TEXT_CRATE, TEXT_RECEIPT, TEXT_QUILL),
        "DELETE FROM `spell_dbc` WHERE `ID` IN (%s);" % ids(spells),
        "DELETE FROM `skilllineability_dbc` WHERE `ID` IN (%s);" % ids(s[0] for s in MOUNT_SPELLS + PET_SPELLS),
        "DELETE FROM `faction_dbc` WHERE `ID` IN (%s);" % ids(f[0] for f in FACTIONS),
        "DELETE FROM `chartitles_dbc` WHERE `ID` IN (%s);" % ids(t[0] for t in TITLES),
        "DELETE FROM `currencytypes_dbc` WHERE `ID` = %d;" % CURRENCY_ID,
        "DELETE FROM `itemextendedcost_dbc` WHERE `ID` IN (%s);" % ids(COSTS),
        "",
    ]
    with open(UNINSTALL, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", UNINSTALL)


if __name__ == "__main__":
    main()
